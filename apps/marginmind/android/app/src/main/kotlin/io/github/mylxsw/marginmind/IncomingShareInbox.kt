package io.github.mylxsw.marginmind

import android.content.Context
import android.content.Intent
import android.net.Uri
import android.os.Handler
import android.os.Looper
import android.provider.OpenableColumns
import androidx.core.content.IntentCompat
import io.flutter.plugin.common.BinaryMessenger
import io.flutter.plugin.common.MethodChannel
import org.json.JSONArray
import org.json.JSONObject
import java.io.File
import java.util.UUID
import java.util.concurrent.Executors

/** Copies temporary URI grants before acknowledging handoff. No I/O on the UI thread. */
class IncomingShareInbox(context: Context, messenger: BinaryMessenger) {
    private val app = context.applicationContext
    private val root = File(app.filesDir, "incoming")
    private val worker = Executors.newSingleThreadExecutor()
    private val main = Handler(Looper.getMainLooper())
    private val channel = MethodChannel(messenger, "marginmind/incoming_share")
    @Volatile private var closed = false

    init {
        worker.execute {
            root.mkdirs()
            root.listFiles()?.filter { System.currentTimeMillis() - it.lastModified() > 86_400_000 }
                ?.forEach { it.deleteRecursively() }
        }
        channel.setMethodCallHandler { call, result ->
            when (call.method) {
                "pending" -> worker.execute {
                    val batches = root.listFiles()?.sortedBy { it.name }?.mapNotNull { directory ->
                        val manifest = File(directory, "manifest.json")
                        if (!manifest.isFile || File(directory, "completed").exists()) null else try {
                            val json = JSONObject(manifest.readText())
                            val files = json.optJSONArray("files") ?: JSONArray()
                            mutableMapOf<String, Any>("id" to directory.name).apply {
                                put("files", (0 until files.length()).map { index ->
                                    val file = files.getJSONObject(index)
                                    val name = file.getString("name")
                                    // Resolve only names generated by this inbox, never an external path.
                                    val stored = file.getString("stored")
                                    require(stored == File(stored).name && !stored.contains('\\') && stored !in listOf(".", ".."))
                                    mapOf("name" to name, "path" to File(directory, stored).absolutePath)
                                })
                                for (key in listOf("url", "title", "error")) {
                                    if (json.has(key)) put(key, json.getString(key))
                                }
                            }
                        } catch (_: Exception) { mapOf("id" to directory.name, "error" to "unavailable") }
                    } ?: emptyList()
                    main.post { if (!closed) result.success(batches) }
                }
                "complete" -> {
                    val id = call.argument<String>("id")
                    if (id == null || !id.matches(Regex("[A-Za-z0-9-]{1,80}"))) {
                        result.error("invalid_request", null, null)
                    } else worker.execute {
                        val acknowledged = runCatching {
                            val directory = File(root, id)
                            if (directory.exists()) {
                                File(directory, "completed").writeBytes(byteArrayOf())
                                directory.deleteRecursively()
                            }
                        }.isSuccess
                        main.post {
                            if (!closed) {
                                if (acknowledged) result.success(null) else result.error("cleanup_failed", null, null)
                            }
                        }
                    }
                }
                else -> result.notImplemented()
            }
        }
    }

    fun capture(intent: Intent?) {
        if (intent?.action !in listOf(Intent.ACTION_SEND, Intent.ACTION_SEND_MULTIPLE, Intent.ACTION_VIEW)) return
        val incoming = intent ?: return
        worker.execute {
            val directory = File(root, "${System.currentTimeMillis()}-${UUID.randomUUID()}")
            directory.mkdirs()
            var manifest = JSONObject()
            try {
                val uris = when (incoming.action) {
                    Intent.ACTION_SEND_MULTIPLE ->
                        IntentCompat.getParcelableArrayListExtra(incoming, Intent.EXTRA_STREAM, Uri::class.java) ?: emptyList()
                    Intent.ACTION_VIEW -> listOfNotNull(incoming.data)
                    else -> listOfNotNull(IntentCompat.getParcelableExtra(incoming, Intent.EXTRA_STREAM, Uri::class.java))
                }.toMutableList()
                // Some file providers send ClipData without EXTRA_STREAM.
                if (uris.isEmpty() && incoming.action != Intent.ACTION_VIEW) {
                    incoming.clipData?.let { clip ->
                        for (index in 0 until clip.itemCount.coerceAtMost(21)) {
                            clip.getItemAt(index).uri?.let { uris.add(it) }
                        }
                    }
                }
                val documents = uris.filter { it.scheme?.lowercase() !in listOf("http", "https") }.distinct()
                require(documents.size <= 20) { "limit" }
                val files = JSONArray()
                var total = 0L
                for ((index, uri) in documents.withIndex()) {
                    // Never turn an exported activity into a reader of private file:// paths.
                    require(uri.scheme == "content") { "unsupported" }
                    val name = displayName(uri, incoming.type)
                    val limit = IncomingSharePolicy.limit(name)
                    val file = File(directory, "$index.${name.substringAfterLast('.').lowercase()}")
                    app.contentResolver.openInputStream(uri).use { input ->
                        requireNotNull(input)
                        file.outputStream().use { output ->
                            val buffer = ByteArray(64 * 1024)
                            var size = 0L
                            while (true) {
                                val read = input.read(buffer)
                                if (read < 0) break
                                size += read
                                total += read
                                require(size <= limit && total <= 512L * 1024 * 1024) { "limit" }
                                output.write(buffer, 0, read)
                            }
                            require(size > 0) { "unsupported" }
                        }
                    }
                    files.put(JSONObject().put("name", name).put("stored", file.name))
                }
                if (files.length() > 0) {
                    manifest.put("files", files)
                } else {
                    val text = if (incoming.action == Intent.ACTION_VIEW) incoming.dataString.orEmpty()
                        else incoming.getCharSequenceExtra(Intent.EXTRA_TEXT)?.toString()?.takeIf { it.isNotBlank() }
                            ?: uris.firstOrNull()?.toString().orEmpty()
                    val url = IncomingSharePolicy.url(text) ?: throw IllegalArgumentException("unsupported")
                    manifest.put("url", url)
                }
                incoming.getStringExtra(Intent.EXTRA_SUBJECT)?.take(200)?.let { manifest.put("title", it) }
            } catch (error: Exception) {
                directory.listFiles()?.forEach { it.deleteRecursively() }
                manifest = JSONObject().put("error", if (error.message in listOf("limit", "unsupported")) error.message else "unavailable")
            }
            try {
                val staging = File(directory, "manifest.tmp")
                staging.writeText(manifest.toString())
                check(staging.renameTo(File(directory, "manifest.json")))
                main.post { if (!closed) channel.invokeMethod("changed", null) }
            } catch (_: Exception) {
                directory.deleteRecursively()
                main.post { if (!closed) channel.invokeMethod("failed", null) }
            }
        }
    }

    private fun displayName(uri: Uri, type: String?): String {
        val raw = app.contentResolver.query(uri, arrayOf(OpenableColumns.DISPLAY_NAME), null, null, null)?.use {
            if (it.moveToFirst()) it.getString(0) else null
        } ?: uri.lastPathSegment.orEmpty()
        val name = raw.replace(Regex("[/\\\\\\x00-\\x1f]"), "_").takeLast(200)
        if (name.contains('.')) return name
        return when (type ?: app.contentResolver.getType(uri)) {
            "application/pdf" -> "${name.ifEmpty { "document" }}.pdf"
            "application/epub+zip" -> "${name.ifEmpty { "document" }}.epub"
            else -> name
        }
    }

    fun close() {
        closed = true
        channel.setMethodCallHandler(null)
        worker.shutdown()
    }
}

internal object IncomingSharePolicy {
    fun limit(name: String): Long = when (name.substringAfterLast('.', "").lowercase()) {
        "pdf" -> 256L * 1024 * 1024
        "mobi", "azw", "azw3" -> 500L * 1024 * 1024
        "epub", "md", "markdown" -> 64L * 1024 * 1024
        else -> throw IllegalArgumentException("unsupported")
    }

    fun url(text: String): String? {
        val links = Regex("https?://[^\\s<>\"\\x00-\\x1f]+", RegexOption.IGNORE_CASE).findAll(text.take(64 * 1024))
        for (match in links) {
            var candidate = match.value.trimEnd('.', ',', ';', '!', '?', '，', '。', '；', '！', '？')
            for ((open, close) in listOf('(' to ')', '[' to ']', '{' to '}', '（' to '）', '【' to '】', '《' to '》')) {
                var excess = candidate.count { it == close } - candidate.count { it == open }
                var end = candidate.length
                while (excess > 0 && end > 0 && candidate[end - 1] == close) { end--; excess-- }
                candidate = candidate.substring(0, end)
            }
            val valid = runCatching {
                val uri = Uri.parse(candidate)
                val host = uri.host.orEmpty()
                uri.scheme?.lowercase() in listOf("http", "https") &&
                    (host.contains('.') || host == "localhost" || host.contains(':')) &&
                    !host.startsWith('.') && !host.contains("..") && uri.userInfo.isNullOrEmpty() &&
                    (uri.port == -1 || uri.port in 1..65535) && !candidate.contains('\\')
            }.getOrDefault(false)
            if (valid) return candidate
        }
        return null
    }
}
