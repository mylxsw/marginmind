import 'package:flutter/material.dart';
import 'package:flutter/gestures.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:marginmind/app/providers.dart';
import 'package:marginmind/features/workspace/widgets/mind_map_canvas.dart';
import 'package:marginmind/features/workspace/widgets/reader_sidebar.dart';
import 'package:marginmind/features/workspace/workspace_controller.dart';
import 'package:marginmind/settings/app_settings.dart';
import 'package:mm_design/mm_design.dart';
import 'package:mm_pdf/mm_pdf.dart';

import 'reader_navigation_test.dart' show openReader;

void main() {
  testWidgets('outline is one line with full tooltip and resizing persists', (tester) async {
    final r = await openReader(tester);
    const title = '很长的章节标题：数字化转型的组织架构与管理流程，以及实际案例';
    r.pdf.debugReport(pageCount: 164, page: 24, outline: const [MMPdfOutlineItem(title: title, page: 20)]);
    r.controller.showReaderPanel(ReaderPanelMode.outline);
    await tester.pumpAndSettle();
    expect(r.container.read(workspaceProvider('demo-1')).sidebarVisible, isTrue);
    final text = tester.widget<Text>(find.text(title));
    expect(text.maxLines, 1);
    expect(text.overflow, TextOverflow.ellipsis);
    expect(find.byTooltip(title), findsOneWidget);
    final sidebar = find.byType(ReaderSidebar);
    final before = tester.getSize(sidebar).width;
    await tester.drag(find.byKey(const ValueKey('reader-sidebar-resize')), const Offset(50, 0));
    await tester.pumpAndSettle();
    final after = tester.getSize(sidebar).width;
    expect(after, greaterThan(before));
    expect(r.container.read(sharedPreferencesProvider).getDouble('settings.readerSidebarWidth'), after);
    r.controller.toggleReaderPanel();
    await tester.pumpAndSettle();
    r.controller.toggleReaderPanel();
    await tester.pumpAndSettle();
    expect(tester.getSize(sidebar).width, after);
    r.container.invalidate(settingsProvider);
    expect(r.container.read(settingsProvider).readerSidebarWidth, after);
    expect(tester.takeException(), isNull);
  });

  testWidgets('reader controls are compact; progress appears on hover and divider restores panes', (tester) async {
    final r = await openReader(tester);
    r.controller.toggleReaderPanel();
    await tester.pumpAndSettle();
    expect(r.container.read(workspaceProvider('demo-1')).sidebarVisible, isTrue);
    r.controller.toggleReaderPanel();
    await tester.pumpAndSettle();
    expect(r.container.read(workspaceProvider('demo-1')).sidebarVisible, isTrue);
    expect(find.text('Reading Appearance'), findsNothing);
    final toolbar = find.byType(MMToolbar);
    final group = find.descendant(of: toolbar, matching: find.byType(MMToolbarGroup)).last;
    expect(tester.getRect(group).right, closeTo(tester.getRect(toolbar).right - MMSpacing.m, .01));
    expect(find.byTooltip('Zoom In'), findsNWidgets(2));
    expect(find.byTooltip('Zoom Out'), findsNWidgets(2));
    await tester.tap(find.byKey(const ValueKey('reader-zoom')));
    await tester.pumpAndSettle();
    expect(find.text('Fit Width'), findsOneWidget);
    expect(find.text('Fit Page'), findsOneWidget);
    expect(find.text('Actual Size'), findsOneWidget);
    expect(find.text('Zoom In'), findsNothing);
    expect(find.text('Zoom Out'), findsNothing);
    await tester.tap(find.text('Fit Width'));
    await tester.pumpAndSettle();
    final progress = find.byKey(const ValueKey('reader-page-progress'));
    expect(progress, findsOneWidget);
    double thumbRadius() =>
        (SliderTheme.of(tester.element(progress)).thumbShape! as RoundSliderThumbShape).enabledThumbRadius;
    final mouse = await tester.createGesture(kind: PointerDeviceKind.mouse);
    await mouse.addPointer(location: Offset.zero);
    await mouse.moveTo(tester.getCenter(find.byKey(const ValueKey('pdf-placeholder-c1'))));
    await tester.pumpAndSettle();
    expect(thumbRadius(), 0);
    expect(thumbRadius(), 0, reason: 'hovering the page body must not reveal navigation');
    await mouse.moveTo(tester.getCenter(progress));
    await tester.pumpAndSettle();
    expect(thumbRadius(), MMSpacing.xs);
    final sliderTheme = SliderTheme.of(tester.element(progress));
    expect(sliderTheme.activeTrackColor!.r, closeTo(sliderTheme.activeTrackColor!.b, .02));
    expect(sliderTheme.thumbColor!.r, sliderTheme.thumbColor!.g);
    expect((sliderTheme.thumbShape! as RoundSliderThumbShape).elevation, 0);
    expect(find.ancestor(of: progress, matching: find.byType(MMGlass)), findsNothing);
    final readerRect = tester.getRect(find.byKey(const ValueKey('pdf-placeholder-c1')));
    expect(tester.getSize(progress).width, greaterThan(readerRect.width * .6));
    expect(sliderTheme.trackHeight, MMSizes.readerProgressTrack);
    final badge = tester.getRect(find.byKey(const ValueKey('reader-page-badge')));
    expect(badge.center.dx, closeTo(readerRect.center.dx, 1));
    expect(badge.bottom, lessThan(tester.getRect(progress).top));
    await tester.drag(progress, const Offset(100, 0));
    await tester.pumpAndSettle();
    await mouse.moveTo(Offset.zero);
    await tester.pumpAndSettle();
    expect(progress, findsOneWidget);
    expect(thumbRadius(), 0);
    await mouse.removePointer();
    await tester.tap(find.byTooltip('Map Only'));
    await tester.pumpAndSettle();
    expect(r.container.read(workspaceProvider('demo-1')).layout, MMSplitMode.secondary);
    await tester.tap(find.byTooltip('Split'));
    await tester.pumpAndSettle();
    expect(r.container.read(workspaceProvider('demo-1')).layout, MMSplitMode.split);
    await tester.tap(find.byTooltip('Source Only'));
    await tester.pumpAndSettle();
    expect(r.container.read(workspaceProvider('demo-1')).layout, MMSplitMode.primary);
    await tester.tap(find.byTooltip('Split'));
    await tester.pumpAndSettle();
    expect(r.container.read(workspaceProvider('demo-1')).layout, MMSplitMode.split);
    expect(tester.takeException(), isNull);
  });

  testWidgets('map retains viewport across document, outline and layout changes', (tester) async {
    final r = await openReader(tester);
    final canvas = tester.widget<MindMapCanvas>(find.byType(MindMapCanvas));
    expect(mapScale(canvas.transformation.value), 1);
    final saved = Matrix4.identity()
      ..translateByDouble(110, 190, 0, 1)
      ..scaleByDouble(.5, .5, 1, 1);
    canvas.transformation.value = saved;
    await tester.pumpAndSettle();
    r.controller.openDocument('c2');
    await tester.pumpAndSettle();
    expect(canvas.transformation.value, saved);
    r.controller.setMapView(MapViewMode.outline);
    await tester.pumpAndSettle();
    r.controller.setMapView(MapViewMode.map);
    await tester.pumpAndSettle();
    final restored = tester.widget<MindMapCanvas>(find.byType(MindMapCanvas));
    expect(restored.transformation.value, saved);
    r.controller.setLayout(MMSplitMode.primary);
    await tester.pumpAndSettle();
    r.controller.setLayout(MMSplitMode.split);
    await tester.pumpAndSettle();
    expect(restored.transformation.value, saved);
    await tester.tap(find.byTooltip('Actual Size').last);
    await tester.pumpAndSettle();
    expect(mapScale(restored.transformation.value), 1);
    await tester.tap(find.byTooltip('Show Entire Map'));
    await tester.pumpAndSettle();
    expect(mapScale(restored.transformation.value), lessThan(1));
    await tester.tap(find.byTooltip('Locate Selected Node'));
    await tester.pumpAndSettle();
    expect(mapScale(restored.transformation.value), 1);
  });
}
