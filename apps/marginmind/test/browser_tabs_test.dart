import 'package:flutter/foundation.dart';
import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:marginmind/app/navigation.dart';
import 'package:marginmind/features/workspace/widgets/browser_pane.dart';
import 'package:marginmind/features/workspace/workspace_browser.dart';
import 'package:marginmind/features/workspace/workspace_controller.dart';
import 'package:mm_design/mm_design.dart';
import 'package:mm_platform/mm_platform.dart';

import 'helpers.dart';

void main() {
  testWidgets('webpages own sessions; reopening, switching and closing preserve other tabs', (tester) async {
    debugDefaultTargetPlatformOverride = TargetPlatform.linux;
    addTearDown(() => debugDefaultTargetPlatformOverride = null);
    final c = await pumpApp(tester);
    c.read(navigationProvider.notifier).openStudySet('demo-1');
    await tester.pump();
    await tester.pump(const Duration(milliseconds: 16));
    await tester.pump(const Duration(milliseconds: 400));
    await tester.pump();
    final browser = c.read(workspaceBrowserProvider('demo-1').notifier);
    final workspace = c.read(workspaceProvider('demo-1').notifier);
    final aUrl = Uri.parse('https://example.com/a');
    browser.open(aUrl);
    final a = c.read(workspaceBrowserProvider('demo-1')).session!;
    a.title = 'First webpage';
    a.canGoBack = true;
    browser.open(Uri.parse('https://example.com/b'));
    final b = c.read(workspaceBrowserProvider('demo-1')).session!;
    b.title = 'Second webpage';
    await tester.pump();
    await tester.pump(const Duration(milliseconds: 16));
    await tester.pump(const Duration(milliseconds: 400));
    await tester.pump();
    expect(a.id, isNot(b.id));
    expect(find.byType(BrowserPane, skipOffstage: false), findsNWidgets(2));
    expect(find.byType(BrowserPane), findsOneWidget);
    expect(tester.widget<BrowserPane>(find.byType(BrowserPane)).session, same(b));
    expect(find.byIcon(MMIcons.history), findsNothing);
    expect(find.byIcon(MMIcons.stop), findsOneWidget);
    expect(find.byKey(const ValueKey('browser-convert')), findsOneWidget);
    browser.open(aUrl);
    await tester.pump();
    await tester.pump(const Duration(milliseconds: 16));
    await tester.pump(const Duration(milliseconds: 400));
    await tester.pump();
    expect(c.read(workspaceBrowserProvider('demo-1')).pages.length, 2);
    expect(c.read(workspaceBrowserProvider('demo-1')).session, same(a));
    expect(a.canGoBack, isTrue);
    workspace.activateTab(WorkspaceTab.documents);
    await tester.pump();
    await tester.pump(const Duration(milliseconds: 16));
    await tester.pump(const Duration(milliseconds: 400));
    await tester.pump();
    expect(c.read(workspaceBrowserProvider('demo-1')).visible, isFalse);
    expect(a.disposed || b.disposed, isFalse);
    browser.show(b.id);
    await tester.pump();
    await tester.pump(const Duration(milliseconds: 16));
    await tester.pump(const Duration(milliseconds: 400));
    await tester.pump();
    expect(browser.beginConversion(a.id), isTrue);
    expect(browser.beginConversion(b.id), isFalse);
    browser.endConversion();
    workspace.closeTab('browser:${a.id}');
    await tester.pump();
    await tester.pump(const Duration(milliseconds: 16));
    await tester.pump(const Duration(milliseconds: 400));
    await tester.pump();
    expect(a.disposed, isTrue);
    expect(browser.beginConversion(a.id), isFalse);
    expect(b.disposed, isFalse);
    expect(c.read(workspaceBrowserProvider('demo-1')).session, same(b));
    workspace.closeTab('browser:${b.id}');
    await tester.pump();
    await tester.pump(const Duration(milliseconds: 16));
    await tester.pump(const Duration(milliseconds: 400));
    await tester.pump();
    expect(b.disposed, isTrue);
    expect(c.read(workspaceBrowserProvider('demo-1')).pages, isEmpty);
    expect(c.read(workspaceProvider('demo-1')).tabs.activeId, WorkspaceTab.documents.id);
    await tester.pumpWidget(const SizedBox.shrink());
    debugDefaultTargetPlatformOverride = null;
  });

  for (final width in [1280.0, 900.0]) {
    testWidgets('16 tabs scroll and search without covering right controls at $width', (tester) async {
      debugDefaultTargetPlatformOverride = TargetPlatform.linux;
      addTearDown(() => debugDefaultTargetPlatformOverride = null);
      final c = await pumpApp(tester, size: Size(width, 820));
      c.read(navigationProvider.notifier).openStudySet('demo-1');
      await tester.pump();
      await tester.pump(const Duration(milliseconds: 16));
      await tester.pump(const Duration(milliseconds: 400));
      await tester.pump();
      final browser = c.read(workspaceBrowserProvider('demo-1').notifier);
      final sessions = <BrowserSession>[];
      for (var i = 0; i < 16; i++) {
        browser.open(Uri.parse('https://example.com/article-$i'));
        final s = c.read(workspaceBrowserProvider('demo-1')).session!;
        s.title = 'Web article $i';
        sessions.add(s);
      }
      await tester.pump();
      await tester.pump(const Duration(milliseconds: 16));
      await tester.pump(const Duration(milliseconds: 400));
      await tester.pump();
      final strip = tester.getRect(find.byKey(const ValueKey('workspace-main-tabs')));
      final controls = tester.getRect(find.byKey(const ValueKey('workspace-layout-controls')));
      final menu = find.byKey(const ValueKey('workspace-tab-overflow'));
      expect(strip.right, lessThanOrEqualTo(controls.left));
      expect(tester.getRect(menu).right, lessThanOrEqualTo(controls.left));
      expect(find.byKey(ValueKey('workspace-tab-browser:${sessions.last.id}')).hitTestable(), findsOneWidget);
      final list = tester.state<ScrollableState>(
        find.descendant(of: find.byKey(const ValueKey('workspace-main-tabs')), matching: find.byType(Scrollable)).first,
      );
      final offset = list.position.pixels;
      await tester.tap(find.byKey(const ValueKey('workspace-tabs-scroll-left')));
      await tester.pump();
      await tester.pump(const Duration(milliseconds: 16));
      await tester.pump(const Duration(milliseconds: 400));
      await tester.pump();
      expect(list.position.pixels, lessThan(offset));
      await tester.tap(menu);
      await tester.pump();
      await tester.pump(const Duration(milliseconds: 16));
      await tester.pump(const Duration(milliseconds: 400));
      await tester.pump();
      await tester.enterText(find.byKey(const ValueKey('workspace-tab-search')), 'Web article 3');
      await tester.pump();
      await tester.pump(const Duration(milliseconds: 16));
      await tester.pump(const Duration(milliseconds: 400));
      await tester.pump();
      final row = find.byKey(ValueKey('workspace-tab-menu-browser:${sessions[3].id}'));
      expect(row, findsOneWidget);
      expect(find.byKey(ValueKey('workspace-tab-menu-browser:${sessions[4].id}')), findsNothing);
      await tester.tap(row);
      await tester.pump();
      await tester.pump(const Duration(milliseconds: 16));
      await tester.pump(const Duration(milliseconds: 400));
      await tester.pump();
      expect(c.read(workspaceBrowserProvider('demo-1')).session, same(sessions[3]));
      expect(find.byKey(ValueKey('workspace-tab-browser:${sessions[3].id}')).hitTestable(), findsOneWidget);
      browser.close(sessions[1].id);
      await tester.pump();
      await tester.pump(const Duration(milliseconds: 16));
      await tester.pump(const Duration(milliseconds: 400));
      await tester.pump();
      expect(sessions[1].disposed, isTrue);
      expect(sessions[3].disposed, isFalse);
      expect(c.read(workspaceBrowserProvider('demo-1')).session, same(sessions[3]));
      expect(tester.takeException(), isNull);
      await tester.pumpWidget(const SizedBox.shrink());
      debugDefaultTargetPlatformOverride = null;
    });
  }
}
